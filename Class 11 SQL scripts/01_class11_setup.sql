       CONCAT('Synthetic Training Address ',sample.seq),
       CASE WHEN MOD(sample.seq,2)=1 THEN 'Demo North City' ELSE 'Demo South City' END,
       CONCAT('TEST-PAY-',LPAD(sample.seq,3,'0')),
       CONCAT('TRAINING ONLY: internal case follow-up note ',sample.seq),
       CASE WHEN MOD(sample.seq,2)=1 THEN 'NORTH' ELSE 'SOUTH' END
FROM (
 SELECT ranked.case_id,ranked.customer_id,ranked.seq
 FROM (
   SELECT v.case_id,v.customer_id,
          ROW_NUMBER() OVER (ORDER BY v.case_id) AS seq
   FROM vw_case_context v
   WHERE v.customer_id IS NOT NULL
 ) ranked
 WHERE ranked.seq <= 24
) sample
JOIN customers c ON c.customer_id=sample.customer_id;

