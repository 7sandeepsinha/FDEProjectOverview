CREATE TABLE class11_case_profiles (
  case_id VARCHAR(12) NOT NULL PRIMARY KEY,
  customer_id VARCHAR(12) NOT NULL,
  full_name VARCHAR(80) NOT NULL,
  email VARCHAR(150) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  street_address VARCHAR(160) NOT NULL,
  city VARCHAR(40) NOT NULL,
  payment_reference VARCHAR(40) NOT NULL,
  internal_note VARCHAR(200) NOT NULL,
  assigned_team VARCHAR(10) NOT NULL,
  CONSTRAINT fk_class11_profile_case FOREIGN KEY (case_id)
    REFERENCES support_cases(case_id) ON DELETE RESTRICT,
  CONSTRAINT fk_class11_profile_customer FOREIGN KEY (customer_id)
    REFERENCES customers(customer_id) ON DELETE RESTRICT,
  CONSTRAINT chk_class11_profile_team CHECK (assigned_team IN ('NORTH','SOUTH'))
) ENGINE=InnoDB;

